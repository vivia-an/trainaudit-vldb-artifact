def build_mechanism_precond() -> None:
    rows = read_csv(EVAL / "ablation_s2_results.csv")
    no_precond_traces = {r["trace_path"] for r in rows if r["setting"] == "no_precond"}
    filtered = [
        r for r in rows
        if r["setting"] in {"full", "no_precond"}
        and (r["setting"] == "no_precond" or r["trace_path"] in no_precond_traces)
    ]

    by_setting: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    trace_counts: dict[str, set[str]] = defaultdict(set)
    for r in filtered:
        by_setting[r["setting"]][r["rule_id"]] += int(r["n_violations"])
        trace_counts[r["setting"]].add(r["trace_path"])

    full_total = sum(by_setting["full"].values())
    no_pre_total = sum(by_setting["no_precond"].values())
    out_rows = [
        {
            "setting": "full",
            "clean_traces": len(trace_counts["full"]),
            "total_violations": full_total,
            "delta_vs_full": 0,
            "rules_with_delta_gt0": 0,
            "worst_rule": "",
            "worst_rule_delta": 0,
            "source": "benchmark/eval/ablation_s2_results.csv",
        },
        {
            "setting": "minus_pi_precond",
            "clean_traces": len(trace_counts["no_precond"]),
            "total_violations": no_pre_total,
            "delta_vs_full": no_pre_total - full_total,
            "rules_with_delta_gt0": sum(
                1 for rule, v in by_setting["no_precond"].items()
                if v - by_setting["full"].get(rule, 0) > 0
            ),
            "worst_rule": max(
                by_setting["no_precond"],
                key=lambda rule: by_setting["no_precond"][rule] - by_setting["full"].get(rule, 0),
            ),
            "worst_rule_delta": max(
                by_setting["no_precond"][rule] - by_setting["full"].get(rule, 0)
                for rule in by_setting["no_precond"]
            ),
            "source": "benchmark/eval/ablation_s2_results.csv",
        },
    ]
    write_csv(
        OUT / "mechanism_precond.csv",
        ["setting", "clean_traces", "total_violations", "delta_vs_full", "rules_with_delta_gt0", "worst_rule", "worst_rule_delta", "source"],
        out_rows,
    )


