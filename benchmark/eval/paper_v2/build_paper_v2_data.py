def build_funnel_appendix() -> None:
    counts = read_csv(EVAL / "funnel_counts.csv")
    skip_l3 = read_csv(EVAL / "funnel_skip_l3_results.csv")
    skip_l4 = read_csv(EVAL / "funnel_skip_l4_results.csv")
    skip_l3_total = len(skip_l3)
    skip_l3_fired = sum(1 for r in skip_l3 if r.get("fired") == "1")
    skip_l4_total = len(skip_l4)
    skip_l4_fired = sum(1 for r in skip_l4 if r.get("fired") == "1")
    rows = []
    for r in counts:
        rows.append({
            "kind": "funnel_layer",
            "name": r["layer"],
            "n": r["n_candidates"],
            "rate": r["kept_fraction"],
            "note": r["note"],
        })
    rows.extend([
        {
            "kind": "skip_stress",
            "name": "skip_l3",
            "n": skip_l3_total,
            "rate": f"{skip_l3_fired / skip_l3_total:.4f}" if skip_l3_total else "0",
            "note": f"{skip_l3_fired}/{skip_l3_total} fired on independent clean traces",
        },
        {
            "kind": "skip_stress",
            "name": "skip_l4",
            "n": skip_l4_total,
            "rate": f"{skip_l4_fired / skip_l4_total:.4f}" if skip_l4_total else "0",
            "note": f"{skip_l4_fired}/{skip_l4_total} fired on same-framework cross-trace; L4 rejects are mainly workload-specific",
        },
    ])
    write_csv(OUT / "funnel_appendix.csv", ["kind", "name", "n", "rate", "note"], rows)


