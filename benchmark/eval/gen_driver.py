# ---- Generation logic ---------------------------------------------------


@dataclass
class GenResult:
    bug_id: str
    framework: str
    run_sh: str
    driver_py: str
    smoke_status: str    # "OK" | "BASH_ERR" | "PY_ERR"
    smoke_detail: str = ""
    skipped_reason: str = ""


def _infer_tier(config: Dict[str, Any]) -> str:
    detect = (config.get("detection_method") or "").lower()
    cat = (config.get("category") or "").lower()
    inv = (config.get("invariant") or "").lower()
    blob = " ".join([detect, cat, inv])
    if any(t in blob for t in ("replica", "router", "expert_bias",
                                 "layer_count", "residual", "jitter",
                                 "sqrt_decay")):
        return "T1_FW_METADATA"
    return "T0_PYTORCH"


def _resolve_commits(config: Dict[str, Any]) -> Tuple[str, str]:
    fixed = config.get("fixed_commit") or ""
    buggy = config.get("buggy_commit") or ""
    if fixed and not buggy:
        # Default to the parent of fixed commit
        buggy = f"{fixed}~1"
    return buggy, fixed


def generate_for_bug(bug_dir: Path, *, use_detect: bool = False) -> GenResult:
    cfg_path = bug_dir / "config.json"
    if not cfg_path.exists():
        return GenResult(bug_id=bug_dir.name, framework="?",
                          run_sh="", driver_py="",
                          smoke_status="SKIP",
                          skipped_reason="config.json not found")
    config = json.loads(cfg_path.read_text())
    bug_id = config.get("bug_id", bug_dir.name)
    framework = (config.get("framework") or "").lower()
    spec = _FRAMEWORKS.get(framework)
    if spec is None:
        return GenResult(bug_id=bug_id, framework=framework,
                          run_sh="", driver_py="",
                          smoke_status="SKIP",
                          skipped_reason=f"no template for framework "
                                          f"{framework!r}")
    buggy_commit, fixed_commit = _resolve_commits(config)
    if not fixed_commit:
        return GenResult(bug_id=bug_id, framework=framework,
                          run_sh="", driver_py="",
                          smoke_status="SKIP",
                          skipped_reason="config.json has no fixed_commit")

    # Deterministic per-bug port offset (still inside spec.port_base+0..99)
    port_offset = int(hashlib.md5(bug_id.encode()).hexdigest()[:4], 16) % 100
    spec.port_base = (spec.port_base // 100) * 100 + port_offset

    run_sh = _RUN_SH_TEMPLATE.format(
        bug_id=bug_id, framework=framework,
        title=config.get("title", "")[:100],
        repo=config.get("repo", ""),
        buggy_commit=buggy_commit, fixed_commit=fixed_commit,
        env_var=spec.env_var,
        pre_run_shell=spec.pre_run_shell,
        torchrun_invocation=spec.torchrun_invocation())

    has_detect = (bug_dir / "detect.py").exists()
    template = (_DRIVER_PY_DETECT_TEMPLATE if (use_detect and has_detect)
                else _DRIVER_PY_TEMPLATE)
    driver_py = template.format(
        bug_id=bug_id, framework=framework,
        title=config.get("title", "")[:100],
        buggy_commit=buggy_commit, fixed_commit=fixed_commit,
        detection_method=config.get("detection_method", "T0/T1 rule"),
        trainaudit_pkg=str(TRAINAUDIT_PKG),
        framework_dir_setup=_FW_SETUPS[framework].rstrip(),
        tier_const=_infer_tier(config))

    return GenResult(bug_id=bug_id, framework=framework,
                      run_sh=run_sh, driver_py=driver_py,
                      smoke_status="PENDING")


def smoke_validate(result: GenResult, tmp_dir: Path) -> GenResult:
    """Run `bash -n` and `python -m py_compile` on the generated files."""
    if result.smoke_status == "SKIP":
        return result
    sh_path = tmp_dir / f"{result.bug_id}_run.sh"
    py_path = tmp_dir / f"{result.bug_id}_driver.py"
    sh_path.write_text(result.run_sh)
    py_path.write_text(result.driver_py)
    try:
        bash_chk = subprocess.run(["bash", "-n", str(sh_path)],
                                    capture_output=True, text=True, timeout=10)
        if bash_chk.returncode != 0:
            result.smoke_status = "BASH_ERR"
            result.smoke_detail = bash_chk.stderr[-400:]
            return result
        py_chk = subprocess.run(
            [sys.executable, "-m", "py_compile", str(py_path)],
            capture_output=True, text=True, timeout=20)
        if py_chk.returncode != 0:
            result.smoke_status = "PY_ERR"
            result.smoke_detail = py_chk.stderr[-400:]
            return result
        result.smoke_status = "OK"
        return result
    except subprocess.TimeoutExpired:
        result.smoke_status = "TIMEOUT"
        return result
    except Exception as e:  # noqa: BLE001
        result.smoke_status = "ERR"
        result.smoke_detail = f"{type(e).__name__}: {e}"
        return result


def write_to_bug_dir(bug_dir: Path, result: GenResult) -> None:
    (bug_dir / "trainaudit_run.sh").write_text(result.run_sh)
    (bug_dir / "trainaudit_run.sh").chmod(0o755)
    (bug_dir / "trainaudit_driver.py").write_text(result.driver_py)


# ---- CLI ---------------------------------------------------------------


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bug", help="single bug id, e.g. M-NEW-32")
    ap.add_argument("--all", action="store_true",
                    help="generate for every bug under benchmark/bugs/* "
                          "that lacks trainaudit_run.sh")
    ap.add_argument("--write", action="store_true",
                    help="write generated files to the bug dir; default is "
                          "stdout-only smoke check")
    ap.add_argument("--use-detect", action="store_true", dest="use_detect",
                    help="wrap detect.py via runpy when present; otherwise "
                          "fall back to scaffold")
    ap.add_argument("--bugs-root",
                    default=str(REPO_ROOT / "benchmark" / "bugs"))
    ap.add_argument("--summary-out",
                    default="benchmark/eval/gen_driver_summary.md")
    args = ap.parse_args()

    bugs_root = Path(args.bugs_root)
    targets: List[Path] = []
    if args.bug:
        targets.append(bugs_root / args.bug)
    elif args.all:
        for d in sorted(bugs_root.iterdir()):
            if not d.is_dir():
                continue
            existing = d / "trainaudit_run.sh"
            if existing.exists():
                # If --use-detect is on AND the existing driver is auto-
                # generated AND there's a detect.py we haven't wrapped yet,
                # regenerate. Otherwise skip.
                is_auto = "AUTO-GENERATED" in existing.read_text()[:400]
                has_detect_wrap = (d / "trainaudit_driver.py").exists() and \
                    "runpy.run_path" in (d / "trainaudit_driver.py").read_text()[:600]
                if not (args.use_detect and is_auto
                        and (d / "detect.py").exists()
                        and not has_detect_wrap):
                    continue
            if not (d / "config.json").exists():
                continue
            targets.append(d)
    else:
        ap.error("specify --bug <id> or --all")

    import tempfile
    tmp = Path(tempfile.mkdtemp())

    results: List[GenResult] = []
    for d in targets:
        r = generate_for_bug(d, use_detect=args.use_detect)
        if r.smoke_status != "SKIP":
            r = smoke_validate(r, tmp)
        if args.write and r.smoke_status == "OK":
            write_to_bug_dir(d, r)
        results.append(r)

    # Summary
    counts: Dict[str, int] = {}
    for r in results:
        counts[r.smoke_status] = counts.get(r.smoke_status, 0) + 1
    lines = [
        "# gen_driver summary\n\n",
        f"- Targets processed: **{len(results)}**\n",
        f"- Smoke OK: **{counts.get('OK', 0)}**\n",
        f"- Skipped: {counts.get('SKIP', 0)} (missing config / no fixed_commit / "
        "unsupported framework)\n",
        f"- bash -n failed: {counts.get('BASH_ERR', 0)}\n",
        f"- py_compile failed: {counts.get('PY_ERR', 0)}\n",
        f"- Other: {sum(v for k, v in counts.items() if k not in ('OK','SKIP','BASH_ERR','PY_ERR'))}\n",
        "\n## Per-bug status\n\n",
        "| bug_id | framework | status | note |\n|---|---|---|---|\n",
    ]
    for r in results:
        note = (r.skipped_reason or r.smoke_detail or "").replace("\n", " ")[:80]
        lines.append(f"| {r.bug_id} | {r.framework} | "
                      f"**{r.smoke_status}** | {note} |\n")
    Path(args.summary_out).write_text("".join(lines))

    n_ok = counts.get("OK", 0)
    print(f"gen_driver: {n_ok}/{len(results)} smoke OK -> {args.summary_out}")
    if args.write:
        print(f"({n_ok} bug dirs updated with trainaudit_run.sh + driver)")
    else:
        print("(stdout-only; pass --write to commit to bug dirs)")


if __name__ == "__main__":
    main()
