"""Auto-generate trainaudit_run.sh + trainaudit_driver.py for a bug.

Reads benchmark/bugs/<bug_id>/config.json (and optionally detect.py /
reproduce.sh) and emits a per-framework scaffold that:

  - sets the framework dir env var (DS_DIR / MEGATRON_DIR / OLMO_DIR /
    OLMOCORE_DIR) and trap-restores the original branch
  - checks out BUGGY then FIXED commit (defaults to <fixed>~1 if buggy
    not given)
  - launches trainaudit_driver.py via torchrun with a deterministic port
  - the driver enables trainaudit, runs a {detect.py-derived | minimal
    scaffold} workload, calls run_rules(), and prints the per-bug
    contract line that benchmark/eval/run_all.py parses.

Limitation: the bug-specific *trigger* (model construction, distributed
config) is bug-dependent and cannot be inferred from config.json alone.
gen_driver emits a TODO marker where the trigger goes, plus a "best
guess" copy of detect.py's relevant body when detect.py is present.

The output is marked with `# AUTO-GENERATED — smoke-pending`. Each
generated driver is syntax-validated (`bash -n` + `python -m py_compile`)
before being declared OK; live verification still requires a GPU run.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

REPO_ROOT = Path(__file__).resolve().parents[2]
TRAINAUDIT_PKG = REPO_ROOT / "core" / "trainaudit_pkg"


@dataclass
class FrameworkSpec:
    name: str                    # config.json:framework value
    env_var: str                 # DS_DIR / MEGATRON_DIR / ...
    nproc_per_node: int          # default torchrun world size
    port_base: int               # deterministic port range
    extra_torchrun_args: str = ""
    pre_run_shell: str = ""      # e.g. PYTHONPATH/CUDA_DEVICE_MAX_CONNECTIONS

    def torchrun_invocation(self, script_path_var: str = "$SCRIPT_DIR") -> str:
        return (f'torchrun --nproc_per_node={self.nproc_per_node} '
                f'--master_port=$(({self.port_base} + RANDOM % 100)) '
                f'{self.extra_torchrun_args} '
                f'"{script_path_var}/trainaudit_driver.py"')


_FRAMEWORKS: Dict[str, FrameworkSpec] = {
    "deepspeed": FrameworkSpec(
        name="deepspeed", env_var="DS_DIR",
        nproc_per_node=1, port_base=29560),
    "megatron-lm": FrameworkSpec(
        name="megatron-lm", env_var="MEGATRON_DIR",
        nproc_per_node=2, port_base=29580,
        pre_run_shell=(
            'export PYTHONPATH="$SCRIPT_DIR:$MEGATRON_DIR:${PYTHONPATH:-}"\n'
            '    export CUDA_DEVICE_MAX_CONNECTIONS=1\n'
            '    rm -f tools/__init__.py 2>/dev/null || true\n'
            '    [ -f tools/__init__.py ] || touch tools/__init__.py')),
    "olmo": FrameworkSpec(
        name="olmo", env_var="OLMO_DIR",
        nproc_per_node=1, port_base=29600),
    "olmo-core": FrameworkSpec(
        name="olmo-core", env_var="OLMOCORE_DIR",
        nproc_per_node=1, port_base=29620),
}


# ---- Bash run script template -------------------------------------------


_RUN_SH_TEMPLATE = '''\
#!/bin/bash
# AUTO-GENERATED by benchmark/eval/gen_driver.py — smoke-pending.
# Bug: {bug_id} ({framework})
# Title: {title}
# Generated against: {repo} @ buggy={buggy_commit} fixed={fixed_commit}
# Contract output (to be parsed by benchmark/eval/run_all.py):
#   [{bug_id}] BUG DETECTED: <rule_id>: <message>
#   [{bug_id}] CLEAN: <message>
#   [{bug_id}] FAIL: <stage>: <error>
set -euo pipefail
{env_var}="${{{env_var}:?Set {env_var} to {framework} repo root}}"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

BUGGY_COMMIT="{buggy_commit}"
FIXED_COMMIT="{fixed_commit}"

cd "${env_var}"
ORIG=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || git rev-parse HEAD)
trap 'cd "${env_var}" && git checkout -q "$ORIG" 2>/dev/null || true' EXIT

run_one() {{
    local label="$1" rev="$2"
    echo "===== TrainAudit on {bug_id} $label ($rev) ====="
    cd "${env_var}"
    git checkout -q "$rev"
    {pre_run_shell}
    set +e
    {torchrun_invocation} 2>&1
    set -e
    echo
}}

run_one "BUGGY" "$BUGGY_COMMIT"
run_one "FIXED" "$FIXED_COMMIT"
'''


# ---- Python driver template ---------------------------------------------


_DRIVER_PY_DETECT_TEMPLATE = '''\
"""AUTO-GENERATED TrainAudit driver for {bug_id} ({framework}).

Bug title: {title}
Buggy commit: {buggy_commit}
Fixed commit: {fixed_commit}
Mode: WRAPS detect.py — trainaudit observes the bug-specific trigger
that detect.py already encodes. Generated by gen_driver.py
--use-detect.

The driver:
  1. enables trainaudit BEFORE detect.py runs so all hooks are in place
  2. runpy.run_path("detect.py") triggers the bug
  3. captures detect.py's stdout to surface its built-in verdict alongside
  4. emits combined contract line on rank 0:
       [{bug_id}] BUG DETECTED: <rule_id>: <message>
       [{bug_id}] CLEAN: <message>
       [{bug_id}] FAIL: <stage>: <error>
"""
import io
import os
import runpy
import sys
import traceback


sys.path.insert(0, "{trainaudit_pkg}")

{framework_dir_setup}
import trainaudit


_DETECT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "detect.py")


def _emit(verdict: str, message: str = "") -> None:
    rank = int(os.environ.get("RANK", "0"))
    if rank != 0:
        return
    if message:
        print(f"[{bug_id}] {{verdict}}: {{message}}", flush=True)
    else:
        print(f"[{bug_id}] {{verdict}}", flush=True)


class _Tee:
    def __init__(self, *streams):
        self._streams = streams
    def write(self, x):
        for s in self._streams:
            try:
                s.write(x)
            except Exception:
                pass
    def flush(self):
        for s in self._streams:
            try:
                s.flush()
            except Exception:
                pass


def main():
    trainaudit.enable(tier=trainaudit.Tier.{tier_const}, db_path=":memory:")
    detect_buf = io.StringIO()
    _orig_stdout = sys.stdout
    sys.stdout = _Tee(_orig_stdout, detect_buf)
    detect_err = ""
    try:
        try:
            runpy.run_path(_DETECT_PATH, run_name="__main__")
        except SystemExit:
            pass
        except Exception as e:
            detect_err = f"{{type(e).__name__}}: {{e}}"
            traceback.print_exc(file=_orig_stdout)
    finally:
        sys.stdout = _orig_stdout

    detect_text = detect_buf.getvalue()
    try:
        results = trainaudit.run_rules()
    except Exception as e:
        _emit("FAIL", f"run_rules: {{type(e).__name__}}: {{e}}")
        trainaudit.disable()
        return

    trainaudit.disable()

    violations = [r for r in results if r.violated]
    if violations:
        v = violations[0]
        _emit("BUG DETECTED", f"{{v.rule_id}}: {{v.message}}")
    elif "[BUG]" in detect_text or "BUG DETECTED" in detect_text or \\
         "[RESULT] BUG" in detect_text:
        _emit("BUG DETECTED",
              "detect.py:builtin (no trainaudit rule fired — fallback to detect.py verdict)")
    elif detect_err:
        _emit("FAIL", f"detect.py: {{detect_err}}")
    else:
        _emit("CLEAN",
              "no trainaudit rule fired; detect.py reported no bug")


if __name__ == "__main__":
    main()
'''


_DRIVER_PY_TEMPLATE = '''\
"""AUTO-GENERATED TrainAudit driver for {bug_id} ({framework}).

Bug title: {title}
Buggy commit: {buggy_commit}
Fixed commit: {fixed_commit}
Expected detection: {detection_method}

Generated by benchmark/eval/gen_driver.py — the bug-specific trigger
below is a SCAFFOLD. Adapt it to the framework's actual entrypoint
(pretrain_gpt / olmo_train / etc.) and inject the bug's trigger
condition (e.g. specific config flags, dtype, parallelism).

The contract is to print exactly one of:
  [{bug_id}] BUG DETECTED: <rule_id>: <message>
  [{bug_id}] CLEAN: <no rule fired>
  [{bug_id}] FAIL: <stage>: <error>
on rank 0 stdout.
"""
import os
import sys

# 1) point to local trainaudit package
sys.path.insert(0, "{trainaudit_pkg}")

{framework_dir_setup}
import trainaudit


def _emit(verdict: str, message: str = "") -> None:
    """Print the contract line to rank-0 stdout."""
    rank = int(os.environ.get("RANK", "0"))
    if rank != 0:
        return
    if message:
        print(f"[{bug_id}] {{verdict}}: {{message}}", flush=True)
    else:
        print(f"[{bug_id}] {{verdict}}", flush=True)


def main():
    trainaudit.enable(tier=trainaudit.Tier.{tier_const}, db_path=":memory:")
    try:
        # ============================================================
        # TODO[{bug_id}]: insert bug-specific trigger here.
        # Reference: benchmark/bugs/{bug_id}/detect.py
        # Steps:
        #   1. build framework's training engine (e.g. deepspeed.initialize,
        #      megatron.pretrain, olmo train_loop)
        #   2. call trainaudit.snapshot_build(model, optimizer)
        #   3. exercise the buggy code path (forward/backward/optim.step)
        # ============================================================
        # Default scaffold (no-op): just exercises the trainaudit hooks
        # so the driver runs end-to-end without raising.
        import torch
        import torch.nn as nn
        import torch.optim as optim
        torch.manual_seed(0)
        model = nn.Sequential(nn.Linear(8, 16), nn.Linear(16, 4))
        opt = optim.AdamW(model.parameters(), lr=1e-3)
        trainaudit.snapshot_build(model, opt)
        x = torch.randn(2, 8)
        model(x).pow(2).sum().backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        opt.step()
        # ============================================================

        results = trainaudit.run_rules()
        violations = [r for r in results if r.violated]
        if violations:
            r = violations[0]
            _emit("BUG DETECTED", f"{{r.rule_id}}: {{r.message}}")
        else:
            _emit("CLEAN", "no rule fired in this run")
    except Exception as e:  # noqa: BLE001
        import traceback
        _emit("FAIL", f"runtime: {{type(e).__name__}}: {{e}}")
        sys.stderr.write(traceback.format_exc())
        raise
    finally:
        trainaudit.disable()


if __name__ == "__main__":
    main()
'''


